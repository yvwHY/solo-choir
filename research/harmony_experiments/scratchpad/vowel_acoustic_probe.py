"""vowel_acoustic_probe - offline feasibility of the acoustic route to vowels

The problem: the visual route has a ceiling, because tongue position is invisible
(two vowels share a lip shape) and live mouth shapes land outside the anchors, so
the field blurs (post-mortem: entropy 0.83, one vowel at 56%). The acoustic channel
carries complete vowel information, but v16.2 died on the parts bleeding back in.
The untried remedy is **spectral subtraction**: the parts' output is generated by
us and therefore entirely known, so it can be subtracted from the microphone
spectrum before recognising the vowel.

Experimental design (no new recording):
  training anchors: the five vowel takes from the earlier session, clean
  test data: the five vowel takes from the later session, clean and independent
  three conditions:
    A  clean test audio, classified
    B  test audio with the parts mixed in at 1:1 RMS, classified (simulating live bleed)
    C  as B, but with spectral magnitude subtraction first, using the known signal,
       including a sensitivity check at plus or minus 20 ms of misalignment
  features: log-mel band energies (300-5000 Hz, 24 bands), mean-removed per frame so
  the level does not matter
  classifier: nearest neighbour by cosine similarity to five anchors (the per-frame
  mean of the training set)
Reading it: a high A means the acoustic features can recognise his vowels and
generalise across sessions; B collapsing reproduces the bleed problem; C returning
close to A means the subtraction route works and is worth taking live.
"""
import numpy as np
import soundfile as sf

SR = 44100
NFFT = 2048
HOPF = 1470                      # a 30 Hz frame rate, matching the camera and control channel
LABELS = ["喔", "欸", "咿", "嗚", "啊"]   # vowel labels; they key bank_live.VOWEL_LAYERS


def melfb(nmel=24, fmin=300.0, fmax=5000.0):
    def m(f):
        return 2595 * np.log10(1 + f / 700)

    def im(x):
        return 700 * (10 ** (x / 2595) - 1)
    pts = im(np.linspace(m(fmin), m(fmax), nmel + 2))
    bins = np.floor((NFFT + 1) * pts / SR).astype(int)
    fb = np.zeros((nmel, NFFT // 2 + 1))
    for i in range(nmel):
        a, b, c = bins[i], bins[i + 1], bins[i + 2]
        if b > a:
            fb[i, a:b] = np.linspace(0, 1, b - a)
        if c > b:
            fb[i, b:c] = np.linspace(1, 0, c - b)
    return fb


FB = melfb()
WIN = np.hanning(NFFT)


def frames(x):
    n = (len(x) - NFFT) // HOPF
    return np.stack([x[i * HOPF:i * HOPF + NFFT] * WIN for i in range(n)])


def feats_from_power(P):
    """P of shape (T, nfft/2+1) power spectra to mean-removed log-mel features."""
    E = P @ FB.T
    L = np.log(E + 1e-10)
    return L - L.mean(1, keepdims=True)


def feats(x):
    F = np.fft.rfft(frames(x), axis=1)
    return feats_from_power(np.abs(F) ** 2)


def voiced(x):
    fr = frames(x)
    r = np.sqrt((fr ** 2).mean(1))
    return r >= 0.25 * np.percentile(r, 75)


def classify(F, anchors):
    A = anchors / np.linalg.norm(anchors, axis=1, keepdims=True)
    Fn = F / (np.linalg.norm(F, axis=1, keepdims=True) + 1e-9)
    return (Fn @ A.T).argmax(1)


def acc_report(tag, preds_true):
    ok = np.concatenate([(p == vi) for vi, p in enumerate(preds_true)])
    per = [f"{LABELS[vi]}{(p == vi).mean():.2f}"
           for vi, p in enumerate(preds_true)]
    print(f"{tag}: overall {ok.mean():.2f}  per vowel {' '.join(per)}", flush=True)
    return ok.mean()


def main():
    tr = dict(np.load("scratchpad/lip_sweep2.npz"))
    te = dict(np.load("scratchpad/lip_ring_sweep.npz"))
    ang, _ = sf.read("scratchpad/v171_r1_out.wav", always_2d=True)
    ang = ang.mean(1).astype("float64")
    # take a stretch where the parts are actually sounding, so silence does not make it look easy
    ar = np.sqrt(np.convolve(ang ** 2, np.ones(4410) / 4410, "same"))
    ai = int(np.argmax(ar > np.percentile(ar, 90)))

    anchors = np.array([feats(tr[f"a{v}"].astype("float64"))[
        voiced(tr[f"a{v}"].astype("float64"))].mean(0) for v in range(5)])

    predA, predB, predC, predC20 = [], [], [], []
    rng = np.random.RandomState(20260813)
    for v in range(5):
        x = te[f"a{v}"].astype("float64")
        vm = voiced(x)
        # a different stretch of the parts per vowel, for noise diversity, mixed in at equal RMS
        seg = ang[ai + v * len(x): ai + (v + 1) * len(x)]
        if len(seg) < len(x):
            seg = np.tile(ang[ai:ai + len(x)], 2)[:len(x)]
        g = np.sqrt((x ** 2).mean() / max((seg ** 2).mean(), 1e-12))
        mix = x + seg * g
        predA.append(classify(feats(x)[vm], anchors))
        predB.append(classify(feats(mix)[vm], anchors))
        # C: power-spectrum subtraction, the signal being known and aligned per frame, floored at 0
        for lag, bucket in ((0, predC), (int(0.02 * SR), predC20)):
            known = np.roll(seg * g, lag)      # simulate the live alignment error
            Pm = np.abs(np.fft.rfft(frames(mix), axis=1)) ** 2
            Pk = np.abs(np.fft.rfft(frames(known), axis=1)) ** 2
            bucket.append(classify(
                feats_from_power(np.maximum(Pm - Pk, 0.0))[vm], anchors))

    acc_report("A clean (the across-session ceiling)", predA)
    acc_report("B mixed 1:1 with the parts (live as it stands)", predB)
    acc_report("C subtracted, perfectly aligned", predC)
    acc_report("C subtracted, 20ms off", predC20)


if __name__ == "__main__":
    main()
